-- 0020: Номера с гостями и цены в маршруте предложения
-- Дата: июль 2026
-- Зачем: пересборка блока Costs. Цены всех позиций (номера,
--        активности, трансферы) вводятся ТОЛЬКО в блоке Costs —
--        для учётности всё считается из одного места.
--
--   selected_rooms (jsonb) — выбранные номера отеля:
--     [{"uid","room_id","guests","price"}]
--     uid уникален, чтобы дублировать один тип номера
--     (например 2× Savannah Room с разным числом гостей).
--     price редактируется в Costs, не в карточке отеля.
--
--   price (numeric) — цена для активностей и трансферов
--     (у отеля цена живёт в номерах selected_rooms).
--
-- Ночи считаются автоматически по датам дней, не хранятся.
-- Старое room_ids остаётся для дестинейшенов; в предложении
-- используется selected_rooms.
-- Статус: накачено на STAGING. На PROD — НЕТ.
-- ============================================================

alter table public.day_blocks
  add column selected_rooms jsonb default '[]',
  add column price numeric;