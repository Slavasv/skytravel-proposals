-- ============================================================
-- 0006: Привязка предложения к клиенту CRM
-- Дата: июль 2026
-- Зачем: предложение должно знать своего клиента — тогда в карточке
--        клиента видна вся его история (предложения + ваучеры),
--        а имя клиента подтягивается автоматически.
-- Статус: накачено на STAGING. На PROD — НЕТ.
-- ============================================================

alter table public.proposals
  add column client_id uuid references public.clients(id) on delete set null;

create index proposals_client_idx on public.proposals (client_id);